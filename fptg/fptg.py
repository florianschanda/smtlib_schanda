class Test_Generator(metaclass=ABCMeta):
    def __init__(self, op, vector):
        assert isinstance(op, Float_Operation)
        assert isinstance(vector, dict)
        self.op      = op
        self.vector  = vector
        self.fd      = None
        self.dialect = None
        self.rng     = None

    @abstractmethod
    def generate(self, dialect):
        assert isinstance(dialect, Dialect)

    @abstractmethod
    def dir_name(self):
        pass

    @abstractmethod
    def bench_name(self):
        pass

    def setup_rng(self):
        self.rng = Random_Hierarchy().extend(self.bench_name()).rng()

    def create_file(self, dialect, logic, status, variant=None):
        assert isinstance(dialect, Dialect)
        assert isinstance(logic, str)
        assert isinstance(status, Expectation)
        assert isinstance(variant, str) or variant is None
        dir_name = self.dir_name()
        os.makedirs(os.path.join("bench", dir_name), exist_ok = True)

        extensions = {
            Dialect.SMTLIB2    : "smt2",
            Dialect.MATHSAT    : "smt2_mathsat",
            Dialect.ALTERGO_FP : "smt2_altergo_fp",
            Dialect.CBMC       : "c",
        }
        core_name = "%s%s.%s" % (self.bench_name(),
                                 "_%s" % variant if variant else "",
                                 extensions[dialect])
        file_name = os.path.join("bench",
                                 dir_name,
                                 core_name)
        self.dialect = dialect
        # pylint: disable=consider-using-with
        self.fd = open(file_name, "w", encoding="UTF-8")
        # pylint: enable=consider-using-with

        if dialect == Dialect.CBMC:
            with open(file_name.replace(".c", ".smt2_cbmc"),
                      "w",
                      encoding="UTF-8") as fd:
                fd.write(os.path.join(dir_name, core_name))
                fd.write(" --function=potato")
                fd.write("\n")

        match dialect:
            case Dialect.SMTLIB2:
                self.fd.write("(set-info :smt-lib-version 2.6)\n")
                self.fd.write("(set-logic %s)\n" % logic)
                self.fd.write("(set-info :source "
                              "|Generated by FPTG and PyMPF|)\n")
                self.fd.write("(set-info :license "
                              "|https://www.gnu.org/licenses/gpl-3.0.html|)\n")
                self.fd.write("(set-info :category \"random\")\n")
                self.fd.write("(set-info :status %s)\n" % status.name.lower())
                self.fd.write("\n")
            case _:
                assert False

    def close_file(self):
        match self.dialect:
            case Dialect.SMTLIB2:
                self.fd.write("\n")
                self.fd.write("(check-sat)\n")
                self.fd.write("(exit)\n")
            case _:
                assert False
        self.fd.close()

    def new_line(self):
        self.fd.write("\n")

    def comment(self, s):
        assert isinstance(s, str)
        match self.dialect:
            case Dialect.SMTLIB2:
                self.fd.write("; %s\n" % s)
            case _:
                assert False

    def define_ref_const(self, fmt, name, ref, negate):
        assert isinstance(fmt, Format)
        assert isinstance(name, str)
        assert isinstance(ref, str)
        assert isinstance(negate, bool)
        match self.dialect:
            case Dialect.SMTLIB2:
                self.fd.write("(declare-const %s %s)\n" %
                              (name, fmt.smtlib_sort()))
                if negate:
                    self.fd.write("(assert (= %s (fp.neg %s)))\n" %
                                  (name, ref))
                else:
                    self.fd.write("(assert (= %s %s))\n" % (name, ref))
            case _:
                assert False

    def define_bv_const(self, name, value):
        assert isinstance(name, str)
        assert isinstance(value, BitVector)

        match self.dialect:
            case Dialect.SMTLIB2:
                self.fd.write("(declare-const %s %s)\n" %
                              (name, value.smtlib_sort()))
                self.fd.write("(assert (= %s %s))\n" %
                              (name, value.smtlib_literal()))
            case _:
                assert False

    def define_float_const(self, fmt, name, value):
        assert isinstance(fmt, Format)
        assert isinstance(name, str)
        assert isinstance(value, MPF)

        if value.isFinite():
            to             = total_order(value)
            to_min, to_max = total_order_infinite_range(value)
            to_lower = self.rng.random_int(to_min, to - 1)
            to_upper = self.rng.random_int(to + 1, to_max)
            lower    = from_total_order(to_lower, value)
            upper    = from_total_order(to_upper, value)

        match self.dialect:
            case Dialect.SMTLIB2:
                self.fd.write("(declare-const %s %s)\n" %
                              (name, fmt.smtlib_sort()))
                if value.isZero() or value.isInfinite():
                    if value.isPositive():
                        self.fd.write("(assert (fp.isPositive %s))\n" %
                                      name)
                    else:
                        self.fd.write("(assert (fp.isNegative %s))\n" %
                                      name)
                if value.isFinite():
                    self.fd.write("(assert (fp.leq %s\n" %
                                  lower.smtlib_literals()[1])
                    self.fd.write("                %s\n" % name)
                    self.fd.write("                %s))\n" %
                                  value.smtlib_literals()[1])
                    self.fd.write("(assert (fp.leq %s\n" %
                                  value.smtlib_literals()[1])
                    self.fd.write("                %s\n" % name)
                    self.fd.write("                %s))\n" %
                                  upper.smtlib_literals()[1])
                elif value.isInfinite():
                    self.fd.write("(assert (fp.isInfinite %s))\n" %
                                  name)
                else:
                    assert value.isNaN()
                    self.fd.write("(assert (fp.isNaN %s))\n" %
                                  name)
                if fmt.eb <= 8 and fmt.sb <= 24:
                    # Writing out the string can get too extreme for
                    # large formats, so we just do it for anything up
                    # to a float32
                    self.fd.write("; %s = %s\n" % (name,
                                                   value.to_python_string()))
            case _:
                assert False

    def set_rm(self, modes):
        assert len(modes) >= 1
        assert all(isinstance(mode, Rounding) for mode in modes)

        match self.dialect:
            case Dialect.SMTLIB2:
                self.fd.write("(declare-const rm RoundingMode)\n")
                for mode in Rounding:
                    if mode not in modes:
                        self.fd.write("(assert (not (= rm %s)))\n" %
                                      mode.to_smtlib())
            case _:
                assert False

    def compute_result(self, fmt, name, args):
        assert isinstance(fmt, (Format, BitVector)), str(fmt)
        assert isinstance(name, str)
        assert isinstance(args, list)
        assert all(isinstance(arg, (str, int)) for arg in args)

        match self.dialect:
            case Dialect.SMTLIB2:
                self.fd.write("(declare-const %s %s)\n" %
                              (name, fmt.smtlib_sort()))
                self.fd.write("(assert (= %s (" % name)
                match self.op:
                    case Float_Operation.ADD:
                        self.fd.write("fp.add")
                    case Float_Operation.FP_TO_UBV:
                        self.fd.write("(_ fp.to_ubv %u)" % fmt.width)
                    case Float_Operation.FP_TO_SBV:
                        self.fd.write("(_ fp.to_sbv %u)" % fmt.width)
                    case _:
                        assert False
                if self.op.is_rounded():
                    self.fd.write(" rm")
                for arg in args:
                    self.fd.write(" %s" % arg)
                self.fd.write(")))\n")
            case _:
                assert False

    def emit_vc(self, actual, result, status):
        assert isinstance(actual, str)
        assert isinstance(result, str)
        assert status in (Expectation.SAT,
                          Expectation.UNSAT)

        match self.dialect:
            case Dialect.SMTLIB2:
                if status == Expectation.SAT:
                    self.fd.write("(assert (= %s %s))\n" %
                                  (actual, result))
                else:
                    self.fd.write("(assert (not (= %s %s)))\n" %
                                  (actual, result))
            case _:
                assert False


class Simple_Test(Test_Generator):
    def dir_name(self):
        fmt = self.vector["fmt"]["fmt"]
        fmt_name = self.vector["fmt"]["vec"].kind.name.lower()
        if fmt_name == "float32":
            return os.path.join("fptg_f32",
                                self.op.name.lower())
        elif fmt.eb <= 8 and fmt.sb <= 24:
            return os.path.join("fptg_other_small",
                                self.op.name.lower(),
                                fmt_name)
        else:
            return os.path.join("fptg_other_large",
                                self.op.name.lower(),
                                fmt_name)

    def bench_name(self):
        hf = sha1()
        hf.update(self.vector["fmt"]["vec"].tag().encode("UTF-8"))
        for arg in self.vector["arg"]:
            hf.update(b'|')
            hf.update(arg["vec"].tag().encode("UTF-8"))
        return hf.hexdigest()

    def generate_rounded(self, dialect):
        assert isinstance(dialect, Dialect)

        # Assemble actuals
        args = [None] * 3
        assert len(self.vector["arg"]) == self.op.arity()
        for n in range(self.op.arity()):
            if self.vector["arg"][n]["vec"].kind == \
               Float_Test_Vector.REFERENCE:
                assert n > 0
                args[n] = args[n - 1].new_mpf()
                if self.vector["arg"][n]["vec"].is_negative:
                    S, E, T = args[n].unpack()
                    args[n].pack(1 - S, E, T)
            else:
                args[n] = self.vector["arg"][n]["flt"]

        # Compute result
        context = Context()
        results = {}
        for rm in Rounding:
            ref = context.perform(op   = self.op,
                                  rm   = rm,
                                  arg1 = args[0],
                                  arg2 = args[1],
                                  arg3 = args[2])
            if ref.bv in results:
                results[ref.bv].append(rm)
            else:
                results[ref.bv] = [rm]
        assert len(results) in (1, 2)

        variant_id = 0
        for bv, rounding_modes in sorted(results.items()):
            ref_result = MPF(self.vector["fmt"]["fmt"].eb,
                             self.vector["fmt"]["fmt"].sb,
                             bv)
            variant_id += 1
            for expectation in (Expectation.UNSAT, Expectation.SAT):
                variant = "%u_%s" % (variant_id, expectation.name.lower())
                self.setup_rng()
                self.create_file(dialect, "QF_FP", expectation, variant)
                self.comment("Format: %s" %
                             self.vector["fmt"]["vec"].kind.name)
                for n in range(self.op.arity()):
                    self.comment("Arg%u: %s" %
                                 (n + 1,
                                  self.vector["arg"][n]["vec"].tag()))

                self.new_line()
                for info in context.info_list():
                    self.comment(info)

                self.new_line()
                self.set_rm(rounding_modes)

                for n in range(self.op.arity()):
                    self.new_line()
                    if self.vector["arg"][n]["vec"].kind == \
                       Float_Test_Vector.REFERENCE:
                        self.define_ref_const(
                            fmt    = self.vector["fmt"]["fmt"],
                            name   = "arg%u" % (n + 1),
                            ref    = "arg%u" % n,
                            negate = self.vector["arg"][n]["vec"].is_negative)
                    else:
                        self.define_float_const(
                            fmt   = self.vector["fmt"]["fmt"],
                            name  = "arg%u" % (n + 1),
                            value = self.vector["arg"][n]["flt"])

                self.new_line()
                self.compute_result(fmt  = self.vector["fmt"]["fmt"],
                                    name = "result",
                                    args = ["arg%u" % (n + 1)
                                            for n in range(self.op.arity())])

                self.new_line()
                self.define_float_const(
                    fmt   = self.vector["fmt"]["fmt"],
                    name  = "expect",
                    value = ref_result)

                self.new_line()
                self.emit_vc(actual = "expect",
                             result = "result",
                             status = expectation)

                self.close_file()

    def generate_fp_to_bv(self, dialect):
        assert isinstance(dialect, Dialect)
        assert self.op in (Float_Operation.FP_TO_UBV,
                           Float_Operation.FP_TO_SBV)
        assert len(self.vector["arg"]) == 1
        assert self.op.arity() == 1

        flt = self.vector["arg"][0]["flt"]

        self.setup_rng()

        bv_widths = {1}
        bv_widths.add(self.rng.random_int(2, 7))
        bv_widths.add(8)
        bv_widths.add(self.rng.random_int(9, 31))
        bv_widths.add(32)
        bv_widths.add(self.rng.random_int(33, 63))
        bv_widths.add(64)

        if flt.isFinite():
            flt_q = abs(flt.to_rational())
            low = Rational(1)
            hi  = Rational(2)
            n   = 0
            while hi < flt_q:
                low  = hi
                hi   = hi * Rational(2)
                n   += 1
            assert low == q_pow2(n)
            if n > 0:
                bv_widths.add(n)

        for target_width in sorted(bv_widths):
            context     = Context()
            results     = {}
            unspecified = []
            for rm in Rounding:
                try:
                    ref = context.perform(op   = self.op,
                                          rm   = rm,
                                          arg1 = flt,
                                          arg2 = target_width)
                    bv = ref.to_unsigned_int()
                    if bv in results:
                        results[bv].append(rm)
                    else:
                        results[bv] = [rm]
                except Unspecified:
                    unspecified.append(rm)
            worklist = []
            for ref_bv, modes in sorted(results.items()):
                bv = BitVector(target_width)
                bv.from_unsigned_int(ref_bv)
                worklist.append((False, bv, modes))
            if unspecified:
                bv = BitVector(target_width)
                bv.from_unsigned_int(self.rng.random_int(0, bv.max_unsigned))
                worklist.append((True, bv, unspecified))

            variant_id = 0
            for unspecified, ref_bv, rounding_modes in worklist:
                for expectation in (Expectation.UNSAT, Expectation.SAT):
                    variant_id += 1
                    if unspecified:
                        if expectation == Expectation.UNSAT:
                            variant = "%u_%u_%s" % (target_width,
                                                    variant_id,
                                                    "unspec_1")
                        else:
                            variant = "%u_%u_%s" % (target_width,
                                                    variant_id,
                                                    "unspec_2")
                        actual_expect = Expectation.SAT
                    else:
                        variant = "%u_%u_%s" % (target_width,
                                                variant_id,
                                                expectation.name.lower())
                        actual_expect = expectation

                    self.setup_rng()
                    self.create_file(dialect,
                                     "QF_BVFP",
                                     actual_expect,
                                     variant)
                    self.comment("Format: %s" %
                                 self.vector["fmt"]["vec"].kind.name)
                    self.comment("Target: bv%u" % target_width)
                    for n in range(self.op.arity()):
                        self.comment("Arg%u: %s" %
                                     (n + 1,
                                      self.vector["arg"][n]["vec"].tag()))

                    self.new_line()
                    for info in context.info_list():
                        self.comment(info)

                    self.new_line()
                    self.set_rm(rounding_modes)

                    self.new_line()
                    self.define_float_const(
                        fmt   = self.vector["fmt"]["fmt"],
                        name  = "arg",
                        value = flt)

                    self.new_line()
                    self.compute_result(fmt  = BitVector(target_width),
                                        name = "result",
                                        args = ["arg"])

                    self.new_line()
                    self.define_bv_const(
                        name  = "expect",
                        value = ref_bv)

                    self.new_line()
                    self.emit_vc(actual = "expect",
                                 result = "result",
                                 status = expectation)
                    if unspecified:
                        self.comment("this benchmark exploits unspecified "
                                     "behaviour")

                    self.close_file()

    def generate(self, dialect):
        assert isinstance(dialect, Dialect)

        if self.op in (Float_Operation.FP_TO_UBV,
                       Float_Operation.FP_TO_SBV):
            self.generate_fp_to_bv(dialect)
        elif self.op.is_rounded():
            # For simple tests we just apply the operation (and
            # optionally rounding modes)
            self.generate_rounded(dialect)


def generate(vec):
    tg = Simple_Test(op     = vec["op"],
                     vector = vec)
    tg.generate(Dialect.SMTLIB2)


def build_fp_vectors(rh, arity):
    assert isinstance(rh, Random_Hierarchy)
    assert isinstance(arity, int) and 1 <= arity <= 3

    match arity:
        case 1:
            fmt_iterations   = 5
            input_iterations = 5
        case 2:
            fmt_iterations   = 2
            input_iterations = 2
        case 3:
            fmt_iterations   = 1
            input_iterations = 1

    for full in (False, True):
        name = os.path.join("vectors",
                            "%u_fp%s.json" % (arity,
                                              "" if full else ".reduced"))
        if os.path.isfile(name):
            return

        print("Building [%s]" % name)

        vectors = list(mk_interleaved_fp_vectors(
            base_rh          = rh,
            fp_inputs        = arity,
            fmt_iterations   = fmt_iterations,
            input_iterations = input_iterations,
            full_spectrum    = full))

        with open(name, "w", encoding="UTF-8") as fd:
            json.dump(vectors, fd, indent=2, sort_keys=True)


def main():
    # Some of the rationals get really big...
    sys.set_int_max_str_digits(0)

    # pylint: disable=unused-variable
    ap = argparse.ArgumentParser()
    subp = ap.add_subparsers(required=True,
                             dest="mode")

    ap_vectors = subp.add_parser("build_vectors")

    ap_generate = subp.add_parser("generate")
    ap_generate.add_argument("operation")
    # pylint: enable=unused-variable

    options = ap.parse_args()

    match options.mode:
        case "build_vectors":
            os.makedirs("vectors", exist_ok=True)
            rh = Random_Hierarchy()
            build_fp_vectors(rh, 1)
            build_fp_vectors(rh, 2)

        case "generate":
            try:
                op = Float_Operation[options.operation.upper()]
            except KeyError:
                ap.error("unknown operation")

            if op.has_float_input():
                vectors = load_vectors(os.path.join("vectors",
                                                    "%u_fp.json" % op.arity()),
                                       op)
            else:
                assert False
            print("Loaded %u vectors for test generation." % len(vectors))

            progress = None
            results  = 0
            with multiprocessing.Pool() as pool:
                for _ in pool.imap_unordered(generate, vectors, 5):
                    results += 1
                    new_progress = "%.1f" % (float(results * 100) /
                                             float(len(vectors)))
                    if new_progress != progress:
                        progress = new_progress
                        print("%s%% complete [%u / %u]" % (progress,
                                                           results,
                                                           len(vectors)))

    return 0


if __name__ == "__main__":
    sys.exit(main())
